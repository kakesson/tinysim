"""
Generate the HTML report for every experiment, plus an index page.

    python experiments/build_html.py            # writes html/
    python experiments/build_html.py --into docs/reports

Each report is one self-contained file: the model, every intermediate form of
its equations, the generated simulation code, the results, the figures, and the
script that produced them. Nothing is loaded from the network, so the pages can
be handed out or printed as they are.
"""

import argparse
import pathlib
import subprocess
import sys

import setup_path  # noqa: F401  (lets this run without installing TinySim)
from tinysim import htmlreport

HERE = pathlib.Path(__file__).resolve().parent

#: The title and one-line summary shown on the index page.
EXPERIMENTS = [
    ("01_rc_pipeline",
     "1. From model text to simulation result",
     "An RC circuit followed through every stage of the compiler, and checked "
     "against the solution you would get with pen and paper."),
    ("02_structure_and_sorting",
     "2. The structure of an equation system",
     "Incidence matrices before and after sorting, with and without an "
     "algebraic loop."),
    ("03_hybrid_events",
     "3. Hybrid models",
     "A bouncing ball and a thermostat: state events, state jumps, and "
     "discrete variables."),
    ("04_initialization",
     "4. Initialization is its own system of equations",
     "A tank that starts where its level is not changing, and what that costs "
     "in unknowns."),
    ("05_when_it_does_not_work",
     "5. The errors are part of the teaching material",
     "Four models a tool must reject, including a pendulum that is high index "
     "rather than wrong."),
    ("06_dc_motor",
     "6. One connect rule, two physical domains",
     "Kirchhoff's laws and the balance of torques, generated by the same two "
     "lines of the language."),
    ("07_solvers",
     "7. Fixed step, variable step, and finding events",
     "What each solver choice costs, measured against two models whose answers "
     "are known in advance."),
]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--into", default="html", metavar="DIRECTORY",
                        help="where to write the pages (default: html/)")
    arguments = parser.parse_args()
    target = pathlib.Path(arguments.into)

    written = []
    for stem, title, summary in EXPERIMENTS:
        script = HERE / f"{stem}.py"
        print(f"running {script.name} ...", flush=True)
        finished = subprocess.run(
            [sys.executable, str(script), "--html", str(target)],
            capture_output=True, text=True)
        if finished.returncode != 0:
            print(finished.stdout[-2000:])
            print(finished.stderr[-2000:], file=sys.stderr)
            return 1
        written.append((target / f"{stem}.html", title, summary))

    index = htmlreport.write_index(written, target / "index.html")
    print(f"\nwrote {len(written)} reports and {index}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
